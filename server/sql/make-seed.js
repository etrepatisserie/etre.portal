// CLI: npm run sql:seed — writes server/sql/seed.sql for MySQL from the same starting data the SQLite
// seed uses (server/seed-data.js + server/data/catalog.json): outlets, settings, staff logins, suppliers,
// catalog products, ingredients, opening stock, and — in a clearly marked last block — the 7 fictional
// "(demo)" customers with portal logins.
// Password hashes come from INITIAL_PASSWORDS in server/seed-data.js (each run makes a fresh random salt).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { hashPassword } from '../passwords.js';
import { INITIAL_PASSWORDS, OUTLET_DEFAULTS, DEFAULT_SETTINGS, STAFF, SUPPLIERS, INGREDIENTS, INGREDIENT_OPENING_SCALE, UNAVAILABLE_SKUS, DEMO_CUSTOMERS } from '../seed-data.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const catalog = JSON.parse(fs.readFileSync(path.join(here, '..', 'data', 'catalog.json'), 'utf8'));

const q = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? '1' : '0';
  return `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
};
const row = (vals) => `(${vals.map(q).join(', ')})`;
const outletId = (code) => `(SELECT id FROM outlets WHERE code = ${q(code)})`;
const productId = (sku) => `(SELECT id FROM products WHERE sku = ${q(sku)})`;
const userId = (email) => `(SELECT id FROM users WHERE email = ${q(email)})`;
const stamp = new Date().toISOString().slice(0, 19).replace('T', ' ');
const out = [`-- ============================================================
-- Être Patisserie ERP Portal — starting data (MySQL)
-- Generated by \`npm run sql:seed\` on ${stamp} UTC. Do not edit by hand: change
-- server/seed-data.js or server/data/catalog.json and run it again.
-- Run after schema.sql against YOUR database:  mysql -u DB_USER -p DB_NAME < server/sql/seed.sql
-- (or phpMyAdmin → your database → Import). The tables must be empty.
-- Logins get the initial passwords from server/seed-data.js (INITIAL_PASSWORDS), stored as scrypt hashes;
-- change them after the first sign-in.
-- The last block adds ${DEMO_CUSTOMERS.length} fictional "(demo)" customers for trying the system: delete it for a live database.
-- ============================================================

SET NAMES utf8mb4;
SET time_zone = '+08:00';   -- Kuala Lumpur
START TRANSACTION;
`];

out.push('\n-- ---------- Outlets (bank account numbers are placeholders: fill them in Admin › Settings) ----------');
const ocols = ['code', 'name', 'company_name', 'company_address', 'company_reg_no', 'sst_reg_no', 'bank_name', 'bank_account_name', 'bank_account_no',
  'pickup_address', 'pickup_slots', 'delivery_slots', 'delivery_area', 'email', 'delivery_fee', 'free_delivery_threshold'];
out.push(`INSERT INTO outlets (${ocols.join(', ')}) VALUES`);
out.push(OUTLET_DEFAULTS.map((o) => row(ocols.map((c) => (c in o ? o[c] : DEFAULT_SETTINGS[c])))).join(',\n') + ';');

out.push('\n-- ---------- Settings (JSON-encoded values) ----------');
out.push('INSERT INTO settings (`key`, `value`) VALUES');
out.push(Object.entries(DEFAULT_SETTINGS).map(([k, v]) => row([k, JSON.stringify(v)])).join(',\n') + ';');

out.push('\n-- ---------- Staff logins (head office = outlet NULL, sees both companies) ----------');
out.push('INSERT INTO users (email, password_hash, name, role, customer_id, outlet_id) VALUES');
out.push(STAFF.map((u) => `(${q(u.email)}, ${q(hashPassword(INITIAL_PASSWORDS[u.password]))}, ${q(u.name)}, ${q(u.role)}, NULL, ${u.outlet === 'HQ' ? 'NULL' : outletId(u.outlet)})`).join(',\n') + ';');

out.push('\n-- ---------- Suppliers ----------');
out.push('INSERT INTO suppliers (code, name, contact, email, phone, address) VALUES');
out.push(SUPPLIERS.map(row).join(',\n') + ';');

out.push(`\n-- ---------- Products: wholesale catalog (${catalog.products.length} items from server/data/catalog.json) ----------`);
out.push('INSERT INTO products (sku, name, category, category_code, size, uom, sell_price, moq, recommended_rsp, shelf_life, storage_notes, heating_notes, notes, is_sellable, unit_cost) VALUES');
out.push(catalog.products.map((p) => {
  const cat = catalog.categories[p.category];
  if (!cat) throw new Error(`Unknown category ${p.category} for ${p.sku}`);
  return row([p.sku, p.name, cat.name, p.category, p.size, p.uom, p.price, p.moq, p.rsp, p.shelf_life, p.storage_notes || null, p.heating_notes || null, cat.note || null, 1, 0]);
}).join(',\n') + ';');
for (const sku of UNAVAILABLE_SKUS) out.push(`UPDATE products SET is_available = 0 WHERE sku = ${q(sku)};  -- seasonal`);

out.push('\n-- ---------- Ingredients & packaging (not sellable) ----------');
out.push('INSERT INTO products (sku, name, category, category_code, uom, unit_cost, sell_price, moq, is_sellable) VALUES');
out.push(INGREDIENTS.map(([sku, name, cat, uom, cost]) => row([sku, name, cat, cat === 'Packaging' ? 'PKG' : 'ING', uom, cost, 0, 1, 0])).join(',\n') + ';');

out.push('\n-- ---------- Stock: one row per product per outlet, reorder levels and opening stock for ingredients ----------');
out.push('INSERT INTO product_stock (product_id, outlet_id) SELECT p.id, o.id FROM products p CROSS JOIN outlets o;');
for (const [sku, , , , , reorder, opening] of INGREDIENTS) {
  for (const [code, scale] of Object.entries(INGREDIENT_OPENING_SCALE)) {
    const qty = Math.round(opening * scale);
    out.push(`UPDATE product_stock SET reorder_level = ${reorder}, stock_on_hand = ${qty} WHERE product_id = ${productId(sku)} AND outlet_id = ${outletId(code)};`);
    out.push(`INSERT INTO stock_movements (product_id, outlet_id, type, qty, balance_after, reason, user_id) VALUES (${productId(sku)}, ${outletId(code)}, 'receipt', ${qty}, ${qty}, 'Opening stock', ${userId('admin@demo.test')});`);
  }
}

// ---------- optional demo customers ----------
const demo = out;
demo.push(`\n-- ============================================================
-- OPTIONAL: ${DEMO_CUSTOMERS.length} fictional customers marked "(demo)" with portal logins (initial password:
-- INITIAL_PASSWORDS.customer). No orders are invented. Delete everything from here to COMMIT for a live database.
-- ============================================================`);
demo.push('\nINSERT INTO customers (code, name, outlet_id, contact, email, phone, address, payment_term, is_demo, account_start_date) VALUES');
demo.push(DEMO_CUSTOMERS.map(([code, name, contact, email, phone, address, term, age, , , , outlet]) =>
  `(${q(code)}, ${q(`${name} (demo)`)}, ${outletId(outlet)}, ${q(contact)}, ${q(email)}, ${q(phone)}, ${q(address)}, ${q(term)}, 1, DATE_SUB(CURRENT_DATE, INTERVAL ${age} DAY))`).join(',\n') + ';');
demo.push('\nINSERT INTO users (email, password_hash, name, role, customer_id, outlet_id) VALUES');
demo.push(DEMO_CUSTOMERS.map(([code, , contact, email]) =>
  `(${q(email)}, ${q(hashPassword(INITIAL_PASSWORDS.customer))}, ${q(contact)}, 'customer', (SELECT id FROM customers WHERE code = ${q(code)}), NULL)`).join(',\n') + ';');
demo.push('\nCOMMIT;\n');
fs.writeFileSync(path.join(here, 'seed.sql'), out.join('\n'));

console.log(`Wrote server/sql/seed.sql (${catalog.products.length} catalog products, ${INGREDIENTS.length} ingredients, ${STAFF.length} staff logins, ${DEMO_CUSTOMERS.length} demo customers).`);
